// Regenerate src/constants/dailyVersesBundled.ts — the slim, offline-first
// daily-verse set that ships INSIDE the APK/IPA.
//
// The bundle is deliberately tiny: it only needs to cover the first few
// days so a brand-new user (offline, or before the first CDN pull
// finishes) never sees a blank prayer card. The full 60-day set lives on
// the CDN (pd-text-corpus) and replaces this bundle the moment
// DailyVersesContext's fetch completes.
//
// Usage:
//   node scripts/gen_bundled_verses.mjs <input-dir> [coverageDays]
// e.g.
//   node scripts/gen_bundled_verses.mjs ./_incoming_verses 3
//
// Reads verses_<lang>.json for all 7 languages from <input-dir>, slims
// each verse to the runtime shape (matching dailyVersesService.slim()),
// keeps only days 1..coverageDays, and writes the TS file.

import fs from 'node:fs';
import path from 'node:path';

const LANGS = ['en', 'zh-Hans', 'zh-Hant', 'de', 'fr', 'es', 'pt'];

const inputDir = process.argv[2];
const coverageDays = parseInt(process.argv[3] || '3', 10);
if (!inputDir) {
  console.error('Usage: node scripts/gen_bundled_verses.mjs <input-dir> [coverageDays]');
  process.exit(1);
}

// Slim one upstream verse to the runtime DailyVerse shape. Mirrors
// dailyVersesService.slim() exactly so the bundled fallback and the CDN
// payload are byte-identical in structure. Returns null if the
// language-specific fields are missing (defensive).
function slim(v, lang) {
  const tr = v.translations?.[lang]?.modern;
  const dev = v.devotional?.[lang];
  const prayer = v.prayer?.[lang];
  if (!tr || !dev || !prayer) return null;
  return {
    day: v.day,
    segment: v.segment,
    reference: {
      book: v.reference.book,
      chapter: v.reference.chapter,
      verse: String(v.reference.verse),
      full_reference: v.reference.full_reference,
    },
    modernVersion: tr.version,
    modernText: tr.text,
    meditation: dev.meditation,
    actionStep: dev.action_step,
    prayer,
  };
}

const bundled = {};
let totalKept = 0;
for (const lang of LANGS) {
  const file = path.join(inputDir, `verses_${lang}.json`);
  const raw = JSON.parse(fs.readFileSync(file, 'utf8'));
  const out = [];
  for (const v of raw.verses || []) {
    if (v.day > coverageDays) continue;        // bundle only the first N days
    const s = slim(v, lang);
    if (s) out.push(s);
  }
  // Stable order: day asc, morning before evening — same as the service.
  out.sort((a, b) => a.day - b.day || (a.segment === 'morning' ? -1 : 1));
  bundled[lang] = out;
  totalKept += out.length;
  console.log(`${lang}: kept ${out.length} verses (days 1-${coverageDays})`);
}

const header = `// AUTO-GENERATED by scripts/gen_bundled_verses.mjs — do not edit by hand.
// Slim, offline-first daily-verse bundle shipped inside the APK/IPA.
// Only the first ${coverageDays} day(s) are bundled; the full 60-day set lives on
// the CDN (pd-text-corpus) and supersedes this the moment the first
// DailyVersesContext fetch completes. Regenerate with:
//   node scripts/gen_bundled_verses.mjs ./_incoming_verses ${coverageDays}
import type { LanguageCode } from '../state/TranslationsContext';

export interface DailyVerse {
  day: number;
  segment: 'morning' | 'evening';
  reference: {
    book: string;
    chapter: number;
    verse: string;
    full_reference: string;
  };
  modernVersion: string;
  modernText: string;
  meditation: string;
  actionStep: string;
  prayer: string;
}

// Bundled coverage in days. The CDN file covers 60; this fallback covers
// only the first ${coverageDays} so the prayer card is never blank before the pull.
export const BUNDLED_COVERAGE_DAYS = ${coverageDays};

export const BUNDLED_DAILY_VERSES: Record<LanguageCode, DailyVerse[]> =
`;

const body = JSON.stringify(bundled, null, 2);
const outPath = path.join(process.cwd(), 'src/constants/dailyVersesBundled.ts');
fs.writeFileSync(outPath, header + body + ';\n', 'utf8');

console.log(`\nWrote ${outPath}`);
console.log(`Total bundled entries: ${totalKept} (${coverageDays} days × 2 segments × ${LANGS.length} langs)`);
