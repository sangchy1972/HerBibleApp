// Reads the 7 upstream JSONs and emits a slim bundled TS module with
// day 1-3 morning + evening verses per language. Drops every field the
// app doesn't need (exegesis, copyright_check, traditional translation,
// niv_primary, mood_tags, etc.) so the bundled-into-APK payload stays
// minimal — this is the offline fallback for the first few days only.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = '/Users/liwencao/Desktop/120 verse 7 languages';
const OUT = '/Users/liwencao/HerBibleApp/src/constants/dailyVersesBundled.ts';
const LANGS = ['en', 'zh-Hans', 'zh-Hant', 'de', 'fr', 'es', 'pt'];
const DAYS = [1, 2, 3];

function slim(v) {
  const lang = v.language;
  const tr = v.translations?.[lang]?.modern;
  const dev = v.devotional?.[lang];
  const prayer = v.prayer?.[lang];
  if (!tr || !dev || !prayer) {
    throw new Error(`missing fields for ${lang} day ${v.day} ${v.segment}`);
  }
  return {
    day: v.day,
    segment: v.segment,
    reference: {
      book: v.reference.book,
      chapter: v.reference.chapter,
      verse: String(v.reference.verse),
      full_reference: v.reference.full_reference,
    },
    modernVersion: tr.version,
    modernText: tr.text,
    meditation: dev.meditation,
    actionStep: dev.action_step,
    prayer,
  };
}

const out = {};
for (const lang of LANGS) {
  const data = JSON.parse(readFileSync(join(SRC, `verses_${lang}.json`), 'utf8'));
  const picked = data.verses.filter(v => DAYS.includes(v.day));
  // Sort: day asc, morning before evening so consumers can index by day cleanly.
  picked.sort((a, b) => a.day - b.day || (a.segment === 'morning' ? -1 : 1));
  out[lang] = picked.map(slim);
}

const banner = `// AUTO-GENERATED by scripts/gen_bundled_verses.mjs from
// "120 verse 7 languages" (3-day fallback, 7 languages × 6 verses).
// Do not edit by hand — re-run the generator if the upstream JSON changes.
`;

const ts = `${banner}
import type { LanguageCode } from '../state/TranslationsContext';

export interface DailyVerse {
  day: number;
  segment: 'morning' | 'evening';
  reference: {
    book: string;
    chapter: number;
    verse: string;
    full_reference: string;
  };
  modernVersion: string;
  modernText: string;
  meditation: string;
  actionStep: string;
  prayer: string;
}

export const BUNDLED_DAILY_VERSES: Record<LanguageCode, DailyVerse[]> =
  ${JSON.stringify(out, null, 2)} as const;

export const BUNDLED_COVERAGE_DAYS = ${DAYS.length};
`;

writeFileSync(OUT, ts);
const size = ts.length;
console.log(`Wrote ${OUT}`);
console.log(`Size: ${(size / 1024).toFixed(1)} KB`);
console.log(`Languages: ${LANGS.length}, Days: ${DAYS.length}, Verses/lang: ${DAYS.length * 2}`);
