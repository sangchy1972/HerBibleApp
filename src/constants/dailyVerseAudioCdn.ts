// Daily-verse "listen / 导读" narration audio. Google-TTS reads of the
// four prayer-flow steps (scripture → reflection → simple-step → prayer)
// for each of the 120 verses. Served PUBLICLY from the same R2 bucket as
// the Bible audio (audio.everlandapps.com → herbible-audio-7languages),
// under `dailyverse_4steps_audio/`. No gating — it's free narration of
// already-free content, same posture as the bg music + Bible audio.
//
// **en / es / pt today.** The listen button is hidden for other UI languages
// until their audio is uploaded (see AVAILABLE_DAILY_VERSE_AUDIO_LANGS below,
// and the per-verse MISSING holes for partial uploads).
//
// Filenames carry an unpredictable middle slug, so the app can't build
// them directly — it reads a bundled manifest (constants/
// dailyVerseAudioManifest.ts) that maps each verseId to its four exact
// filenames. That manifest is generated by
// scripts/gen_dailyverse_audio_manifest.mjs from the local audio folder.

// Bucket prefix (without the language segment). Files live under
// <BASE>/<lang>/<filename>, e.g.
//   …/dailyverse_4steps_audio_7languages/en/e_001_evening_john-14-1_01_scripture.mp3
export const DAILY_VERSE_AUDIO_BASE =
  'https://audio.everlandapps.com/dailyverse_4steps_audio_7languages';

// Default language-folder segment. English is the baseline that always
// exists; the URL builders below accept an explicit `lang` so the path is
// already multilingual-ready — only the SET below gates which languages we
// actually point at.
export const DAILY_VERSE_AUDIO_LANG = 'en';

// Languages that have narration mp3s + timestamp .json uploaded to the CDN
// under <BASE>/<lang>/…. es/pt mirror the ENGLISH filenames 1:1 (same slugs),
// so the single bundled manifest serves all three — only this set (plus the
// per-verse holes below) gates what we offer. When another language lands on
// Cloudflare, add its code here after a full-coverage probe.
// ⚠️ EMPTY since daily-verse batch 2 (owner 2026-08-30): batch 2 has NO
// narration audio yet, and the audio manifest maps by BARE verseId
// (m_001…e_060) — ids batch 2 REUSES for different verses. Re-enabling
// without regenerating the manifest from batch-2 recordings would play
// batch-1 audio over batch-2 text (the filenames even embed the old
// references). When batch-2 audio lands: run
// scripts/gen_dailyverse_audio_manifest.mjs against the new files, probe
// full coverage (check_daily_verse_audio.sh), THEN re-add languages here.
// ⚠️ ALSO: the prayer flow now inserts a CONTEXT page after the verse when
// the entry has a context_note (PrayerFlow hasCtxPage, 2026-09-05). The
// narration wiring still assumes listenStep === page — valid only while
// narration and that page are mutually exclusive. Before re-adding langs,
// give PrayerFlow a page→step map that skips the context page (it has no
// clip), or five-page days will narrate the wrong text.
// This set gates ONLY the regular daily-verse narration — holiday narration
// has its own set below (separate folder, separate manifest, untouched by
// batch 2; emptying this one must never silence the holidays again).
export const AVAILABLE_DAILY_VERSE_AUDIO_LANGS = new Set<string>([]);

// Per-language upload HOLES at VERSE granularity — any missing step mp3 hides
// that verse's Listen for that language (a shown button that 404s mid-flow is
// worse than no button). ADD a verseId here if a language's upload is partial.
//
// 2026-07-10: the es m_026–m_050 audio has been uploaded and verified — this
// time against the actual .mp3 files (an earlier check hit only the timing
// .json siblings, which existed while the mp3s did NOT, and wrongly cleared
// these). Spot-checked m_026/m_033/m_038/m_047/m_050 across all four steps:
// all return 200 audio/mpeg. es + pt now have FULL coverage, so the map is
// empty. If a future upload is partial, re-add the verseIds here (run
// check_daily_verse_audio.sh — it sweeps every .mp3, not the .json).
const MISSING_DAILY_VERSE_AUDIO: Record<string, ReadonlySet<string>> = {};

// Resolve a UI language to the narration language we should fetch: the UI
// language itself when its audio exists, otherwise null (caller skips the
// listen control / prefetch — we never silently serve English audio to a
// non-English reader, and we never waste bandwidth pre-warming clips that
// won't be offered).
export function resolveDailyVerseAudioLang(uiLang: string): string | null {
  return AVAILABLE_DAILY_VERSE_AUDIO_LANGS.has(uiLang) ? uiLang : null;
}

// Verse-level availability: the language is recorded AND this specific verse
// has no upload hole. Callers gate the Listen button + prefetch on this.
export function isDailyVerseAudioAvailable(lang: string, verseId: string): boolean {
  if (!AVAILABLE_DAILY_VERSE_AUDIO_LANGS.has(lang)) return false;
  return !MISSING_DAILY_VERSE_AUDIO[lang]?.has(verseId);
}

// Step keys in PRAYER-FLOW PAGE ORDER (page 0..3). Mirrors PrayerFlow's
// SECTIONS = ['verse','meditation','action','prayer'] one-to-one:
//   page 0 verse      → scripture
//   page 1 meditation → reflection
//   page 2 action     → simple-step
//   page 3 prayer     → prayer
export const DAILY_VERSE_AUDIO_STEPS = ['scripture', 'reflection', 'simple-step', 'prayer'] as const;
export type DailyVerseAudioStep = typeof DAILY_VERSE_AUDIO_STEPS[number];

export interface DailyVerseAudioManifest {
  version: number;
  base_url: string;
  step_order: string[];
  // verseId (m_001 / e_001) → { scripture, reflection, simple-step, prayer }
  verses: Record<string, Partial<Record<DailyVerseAudioStep, string>>>;
}

export function dailyVerseAudioUrl(filename: string, lang: string = DAILY_VERSE_AUDIO_LANG): string {
  return `${DAILY_VERSE_AUDIO_BASE}/${lang}/${filename}`;
}

// Holiday-verse narration. Separate bucket prefix from the regular daily-verse
// audio because the holiday verseIds (m_001…e_010 = holiday day index) COLLIDE
// with the regular ones — same id, different audio — so they need a distinct
// folder + manifest + on-device cache. Now EN/ES/PT, mirroring the regular set:
// es/pt reuse the ENGLISH filenames 1:1, so the single bundled manifest serves
// all three. NOTE the language folder is UPPERCASE here (EN/ES/PT) — that's how
// the files are actually laid out under this prefix, unlike the lowercase
// regular-audio folders.
//   <BASE>/<LANG>/<filename>, e.g.
//   …/dailyverse_4steps_audio_7languages_holidays/EN/e_001_new-years-day_evening_01_scripture.mp3
export const HOLIDAY_VERSE_AUDIO_BASE =
  'https://audio.everlandapps.com/dailyverse_4steps_audio_7languages_holidays';

// Holiday narration availability — INDEPENDENT of the regular set above.
// The holiday recordings (10 holidays × morning/evening × 4 steps) predate
// batch 2, live in their own folder + bundled manifest, and were never part
// of the id-collision problem that emptied AVAILABLE_DAILY_VERSE_AUDIO_LANGS.
// This function used to read that shared set, so the batch-2 kill switch
// silently coupled the two — decoupled 2026-09-05.
//
// ⚠️ EMPTY because the files are GONE from the CDN (probed 2026-09-05):
// commit b5faae4 verified …_holidays/EN|ES|PT/ live on 2026-07-08, but every
// probe of those exact URLs now 404s while the regular narration in the SAME
// bucket still 200s — the holiday folder was deleted from R2 some time after
// July, and no local copy was found on this machine. Shipped builds ≤35 still
// offer the button and will hit the 404 on the next holiday (Thanksgiving
// 2026-11-26). When the 80 clips (+ .json timing siblings) are re-uploaded
// under the layout holidayVerseAudioUrl() builds, re-add 'en','es','pt' here —
// nothing else needs touching.
export const AVAILABLE_HOLIDAY_VERSE_AUDIO_LANGS = new Set<string>([]);

export function isHolidayVerseAudioAvailable(lang: string): boolean {
  return AVAILABLE_HOLIDAY_VERSE_AUDIO_LANGS.has(lang);
}

// Holiday counterpart of resolveDailyVerseAudioLang: the UI language itself
// when holiday narration exists for it, otherwise null (no silent fallback
// to English for non-English readers).
export function resolveHolidayVerseAudioLang(uiLang: string): string | null {
  return AVAILABLE_HOLIDAY_VERSE_AUDIO_LANGS.has(uiLang) ? uiLang : null;
}

export function holidayVerseAudioUrl(filename: string, lang: string = DAILY_VERSE_AUDIO_LANG): string {
  // Language folder is UPPERCASE on the CDN (EN/ES/PT).
  return `${HOLIDAY_VERSE_AUDIO_BASE}/${lang.toUpperCase()}/${filename}`;
}
